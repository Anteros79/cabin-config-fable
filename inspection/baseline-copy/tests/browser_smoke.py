"""Browser QA against a disposable visit database; default port 8001."""
import os
from pathlib import Path

from playwright.sync_api import expect, sync_playwright

BASE = os.getenv("CABIN_TEST_URL", "http://127.0.0.1:8001")
OUT = Path("artifacts")
OUT.mkdir(exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.getenv("CHROMIUM_PATH", "/usr/bin/chromium"),
        headless=True, args=["--no-sandbox", "--enable-unsafe-swiftshader"])
    page = browser.new_page(viewport={"width": 1440, "height": 1050}, timezone_id="America/Chicago")
    errors = []
    page.on("pageerror", lambda e: errors.append(str(e)))
    page.goto(BASE)
    expect(page.locator("#cabin-3d canvas")).to_be_visible()
    expect(page.locator("#seat-count")).to_contain_text("176 seats")
    page.locator("#check-date").fill("2026-11-12")
    page.locator("#technician").fill("Demo technician")
    page.locator("#start-check").click()
    expect(page.locator("#visit-status")).to_have_text("Draft")
    page.locator("#layer-bins").uncheck()
    page.locator('[data-view="top"]').click()
    page.locator("canvas").scroll_into_view_if_needed()
    pt = page.evaluate("window.cabinViewer.screenPoint('3A')")
    page.mouse.click(pt["x"], pt["y"])
    expect(page.locator("#inspector h2")).to_have_text("Seat 3A")
    expect(page.locator("#inspector")).to_contain_text("FAKE-SC-1001")
    page.locator("#focus-selection").click()
    assert page.evaluate("window.cabinViewer.camera.position.distanceTo(window.cabinViewer.controls.target)<10")
    page.locator('[data-view="overview"]').click()
    page.locator("#inspector textarea").first.fill("Fictional backrest scuff")
    page.get_by_role("button", name="Record replacement", exact=True).first.click()
    expect(page.locator("#replacement-count")).to_have_text("1")
    page.get_by_role("button", name="Record replacement", exact=True).first.click()
    expect(page.locator("#replacement-count")).to_have_text("2")
    page.locator("#location-jump").select_option("FULL_CABIN")
    page.locator("details.substitute > summary").click()
    page.get_by_role("button", name="Record this substitute").click()
    expect(page.locator("#replacement-count")).to_have_text("3")
    expect(page.locator("#replacement-list")).to_contain_text("FAKE-P-42")
    page.locator("#location-jump").select_option("BIN-L-01")
    page.get_by_role("button", name="Record replacement", exact=True).click()
    expect(page.locator("#replacement-count")).to_have_text("4")
    page.reload()
    expect(page.locator("#replacement-count")).to_have_text("4")
    page.locator("#location-jump").select_option("3A")
    page.locator("#draft-report").click()
    expect(page.locator("#report-title")).to_have_text("Draft · After-action report")
    page.get_by_role("button", name="Close report", exact=True).click()
    page.locator("#complete").click()
    page.locator("#confirm-complete").click()
    expect(page.locator("#report-dialog")).to_be_visible()
    expect(page.locator("#report-content")).to_contain_text("COMPLETED")
    expect(page.locator("#report-content")).to_contain_text("FAKE-P-42")
    expect(page.locator("#report-content")).to_contain_text("DOC-DEV")
    page.locator("#report-dialog").screenshot(path=str(OUT / "report.png"))
    with page.expect_download() as download:
        page.locator("#export-report").click()
    assert download.value.suggested_filename.endswith(".json")
    page.emulate_media(media="print")
    page.pdf(path=str(OUT / "after-action-report.pdf"), format="A4", print_background=True)
    page.emulate_media(media="screen")
    page.get_by_role("button", name="Close report", exact=True).click()
    expect(page.locator("#inspector button.secondary").first).to_be_disabled()
    page.locator("#saved-visits").click()
    expect(page.locator("#history-dialog")).to_be_visible()
    page.locator("#history-list button").first.click()
    expect(page.locator("#history-dialog")).not_to_be_visible()
    page.locator("#tail").fill("N200TL")
    page.locator("#check-date").fill("2026-06-30")
    page.locator("#start-check").click()
    expect(page.locator("#configuration")).to_contain_text("V05")
    page.locator("#check-date").fill("2026-07-01")
    page.locator("#start-check").click()
    expect(page.locator("#configuration")).to_contain_text("V04")
    page.locator("#location-jump").select_option("FULL_CABIN")
    expect(page.locator("#inspector")).to_contain_text("Pending change")
    page.locator("#tail").fill("N000TL")
    page.locator("#start-check").click()
    expect(page.locator("#notice")).to_contain_text("NO_CONFIG")
    assert not errors, errors
    mobile = browser.new_page(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True, timezone_id="America/Chicago")
    mobile.goto(BASE)
    expect(mobile.locator("canvas")).to_be_visible()
    mobile.locator("canvas").scroll_into_view_if_needed()
    bounds = mobile.locator("canvas").bounding_box()
    for seat in ["1A", "1F", "30A", "30F"]:
        point = mobile.evaluate("s=>window.cabinViewer.screenPoint(s)", seat)
        assert bounds["x"] <= point["x"] <= bounds["x"] + bounds["width"]
        assert bounds["y"] <= point["y"] <= bounds["y"] + bounds["height"]
    mobile.locator("#check-date").fill("2026-11-12")
    mobile.locator("#start-check").click()
    expect(mobile.locator("#visit-status")).to_have_text("Draft")
    mobile.locator("#location-jump").select_option("3A")
    mobile.get_by_role("button", name="Record replacement", exact=True).first.click()
    expect(mobile.locator("#replacement-count")).to_have_text("1")
    assert mobile.evaluate("document.documentElement.scrollWidth<=innerWidth")
    mobile.screenshot(path=str(OUT / "mobile.png"), full_page=True)
    browser.close()
    print("Browser workflow passed: WebGL seat selection, focus, replacements, substitutes/panels, bins, persistence, completed report/PDF/JSON, retrofit, missing config, mobile.")
